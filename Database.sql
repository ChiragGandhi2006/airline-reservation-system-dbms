-- 1. Prevent booking if seat is already booked
DELIMITER $$

CREATE TRIGGER trg_before_booking_insert 
BEFORE INSERT ON Booking 
FOR EACH ROW 
BEGIN 
    DECLARE seat_status VARCHAR(20);
    
    SELECT Availability INTO seat_status 
    FROM Seat 
    WHERE SeatID = NEW.SeatID;
    
    IF seat_status = 'Booked' THEN 
        SIGNAL SQLSTATE '45000' 
        SET MESSAGE_TEXT = 'Error: This seat is already booked!';
    END IF;
END $$

DELIMITER ;

-- 2. Mark seat as booked after a confirmed booking
DELIMITER $$

CREATE TRIGGER trg_after_booking_insert 
AFTER INSERT ON Booking 
FOR EACH ROW 
BEGIN 
    IF NEW.BookingStatus = 'Confirmed' THEN 
        UPDATE Seat 
        SET Availability = 'Booked' 
        WHERE SeatID = NEW.SeatID;
    END IF;
END $$

DELIMITER ;

-- 3. Mark seat as available when booking is deleted/canceled
DELIMITER $$

CREATE TRIGGER trg_after_booking_delete 
AFTER DELETE ON Booking 
FOR EACH ROW 
BEGIN 
    IF OLD.BookingStatus = 'Confirmed' THEN 
        UPDATE Seat 
        SET Availability = 'Available' 
        WHERE SeatID = OLD.SeatID;
    END IF;
END $$

DELIMITER ;